func TestSyncOnFreshHomeRendersEveryRoleForEveryHarness(t *testing.T) {
	sys := newSystem(t, t.TempDir())
	addRoles(t, newAgentsDir(t, sys.Home, "tdd"))

	if stdout, code := run(t, sys, "sync"); code != 0 {
		t.Fatalf("exit code = %d, want 0\n%s", code, stdout)
	}

	for _, name := range []string{"explorer", "restricted"} {
		for path, golden := range map[string]string{
			filepath.Join(".claude", "agents", name+".md"):             name + ".claude.md",
			filepath.Join(".codex", "agents", name+".toml"):            name + ".codex.toml",
			filepath.Join(".config", "opencode", "agents", name+".md"): name + ".opencode.md",
		} {
			assertSameFile(t, filepath.Join(sys.Home, path), filepath.Join("..", "harness", "testdata", "golden", golden))
		}
	}
	for _, dir := range []string{".claude/agents", ".codex/agents", ".config/opencode/agents"} {
		entries, err := os.ReadDir(filepath.Join(sys.Home, dir))
		if err != nil || len(entries) != 2 {
			t.Fatalf("~/%s has %d entries, want explorer and restricted only: %v", dir, len(entries), err)
		}
	}
}

// addRoles copies the harness package's Role fixture (roles.yaml with main,
// explorer and restricted, and their prompts) into the agents directory.
func addRoles(t *testing.T, agents string) {
	t.Helper()
	fixture := filepath.Join("..", "harness", "testdata", "agents")
	for _, name := range []string{"roles.yaml", "roles/explorer.md", "roles/restricted.md"} {
		content, err := os.ReadFile(filepath.Join(fixture, name))
		if err != nil {
			t.Fatal(err)
		}
		mustWrite(t, filepath.Join(agents, name), string(content))
	}
}

func assertSameFile(t *testing.T, path, want string) {
	t.Helper()
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	wantContent, err := os.ReadFile(want)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(wantContent) {
		t.Fatalf("%s:\n%s\nwant (%s):\n%s", path, got, want, wantContent)
	}
}

func TestSyncPreservesAndReportsAHandWrittenAgentFileAndReplacesAnOutdatedGeneratedOne(t *testing.T) {
	sys := newSystem(t, t.TempDir())
	addRoles(t, newAgentsDir(t, sys.Home, "tdd"))
	handWritten := filepath.Join(sys.Home, ".claude", "agents", "explorer.md")
	mustWrite(t, handWritten, "---\nname: explorer\ndescription: mine\n---\n\nMy explorer.\n")
	outdated := filepath.Join(sys.Home, ".codex", "agents", "restricted.toml")
	mustWrite(t, outdated, "# generated by overlord from ~/.agents/roles; edit there\nname = \"restricted\"\n")
	conflict := "  conflict  ~/.claude/agents/explorer.md: hand-written agent file; left in place\n"

	stdout, code := run(t, sys, "sync", "--check")
	if code == 0 || !strings.Contains(stdout, conflict) || !strings.Contains(stdout, "  replace   ~/.codex/agents/restricted.toml\n") {
		t.Fatalf("sync --check exit code = %d, stdout:\n%s", code, stdout)
	}

	stdout, code = run(t, sys, "sync")
	if code != 0 || !strings.Contains(stdout, conflict) || !strings.Contains(stdout, "  replaced  ~/.codex/agents/restricted.toml\n") {
		t.Fatalf("sync exit code = %d, stdout:\n%s", code, stdout)
	}
	if got, _ := os.ReadFile(handWritten); string(got) != "---\nname: explorer\ndescription: mine\n---\n\nMy explorer.\n" {
		t.Fatalf("hand-written agent file changed:\n%s", got)
	}
	assertSameFile(t, outdated, filepath.Join("..", "harness", "testdata", "golden", "restricted.codex.toml"))
}

func TestSyncOnFreshHomeWritesTheMainModelForClaudeAndCodexOnly(t *testing.T) {
	sys := newSystem(t, t.TempDir())
	addRoles(t, newAgentsDir(t, sys.Home, "tdd"))

	if stdout, code := run(t, sys, "sync"); code != 0 {
		t.Fatalf("exit code = %d, want 0\n%s", code, stdout)
	}

	var settings struct{ Model string }
	if err := json.Unmarshal([]byte(readFile(t, filepath.Join(sys.Home, ".claude", "settings.json"))), &settings); err != nil || settings.Model != "opus" {
		t.Fatalf("settings.json model = %q, want opus: %v", settings.Model, err)
	}
	if got := readFile(t, filepath.Join(sys.Home, ".codex", "config.toml")); got != "model = \"gpt-6\"\n" {
		t.Fatalf("config.toml:\n%s", got)
	}
	if _, err := os.Lstat(filepath.Join(sys.Home, ".config", "opencode", "opencode.jsonc")); !os.IsNotExist(err) {
		t.Fatalf("OpenCode config was written: %v", err)
	}
}

func TestSyncChangesOnlyTheModelInExistingSettingsAndConfig(t *testing.T) {
	cases := []struct{ name, settings, wantSettings, config, wantConfig string }{
		{
			name:         "model present",
			settings:     "{\n  \"env\": {\n    \"A\": \"1\"\n  },\n  \"model\":   \"sonnet\",\n  \"permissions\": {\"allow\": [\"Bash(ls:*)\"]},\n" + overlordHook + "\n}\n",
			wantSettings: "{\n  \"env\": {\n    \"A\": \"1\"\n  },\n  \"model\":   \"opus\",\n  \"permissions\": {\"allow\": [\"Bash(ls:*)\"]},\n" + overlordHook + "\n}\n",
			config:       "# My Codex config\nmodel = \"gpt-5\"  # pinned\nmodel_provider = \"sleev\"\n\n[features]\nmodel = \"not top level\"\n",
			wantConfig:   "# My Codex config\nmodel = \"gpt-6\"  # pinned\nmodel_provider = \"sleev\"\n\n[features]\nmodel = \"not top level\"\n",
		},
		{
			name:         "model absent",
			settings:     "{\n    \"theme\": \"dark\",\n" + overlordHook + "\n}",
			wantSettings: "{\n    \"model\": \"opus\",\n    \"theme\": \"dark\",\n" + overlordHook + "\n}",
			config:       "approval_policy = \"never\"\n\n[agents]\nmodel = \"gpt-5\"\n",
			wantConfig:   "model = \"gpt-6\"\napproval_policy = \"never\"\n\n[agents]\nmodel = \"gpt-5\"\n",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			sys := newSystem(t, t.TempDir())
			addRoles(t, newAgentsDir(t, sys.Home, "tdd"))
			settings := filepath.Join(sys.Home, ".claude", "settings.json")
			config := filepath.Join(sys.Home, ".codex", "config.toml")
			mustWrite(t, settings, tc.settings)
			mustWrite(t, config, tc.config)

			stdout, code := run(t, sys, "sync")

			if code != 0 {
				t.Fatalf("exit code = %d, want 0\n%s", code, stdout)
			}
			if got := readFile(t, settings); got != tc.wantSettings {
				t.Errorf("settings.json:\n%s\nwant:\n%s", got, tc.wantSettings)
			}
			if got := readFile(t, config); got != tc.wantConfig {
				t.Errorf("config.toml:\n%s\nwant:\n%s", got, tc.wantConfig)
			}
			for _, line := range []string{"  updated   ~/.claude/settings.json: main Model\n", "  updated   ~/.codex/config.toml: main Model\n"} {
				if !strings.Contains(stdout, line) {
					t.Errorf("stdout lacks %q:\n%s", line, stdout)
				}
			}
		})
	}
}

// overlordHook is a settings.json hooks member that already runs Overlord's
// Sync at session start, so a test of the Model sees only the Model change.
const overlordHook = `  "hooks": {"SessionStart": [{"hooks": [{"type": "command", "command": "overlord sync --quiet"}]}]}`
