const header = "# generated by overlord from .agents/roles; edit there\n"

// rolesProject returns a Project already set up except for its Roles, with
// .agents/roles.yaml defining a main Role (no agent file) and reviewer.
func rolesProject(t *testing.T) string {
	t.Helper()
	project := completeProject(t)
	mustWrite(t, filepath.Join(project, ".agents", "roles.yaml"), `main:
  description: The main agent.
  models: {claude: opus, codex: gpt-6, opencode: openai/gpt-6}
reviewer:
  description: Reviews diffs.
  readOnly: true
  models: {claude: sonnet, codex: gpt-6-mini, opencode: openai/gpt-6-mini}
  prompt: roles/reviewer.md
`)
	mustWrite(t, filepath.Join(project, ".agents", "roles", "reviewer.md"), "Review the diff.\n")
	return project
}

func TestSetupRendersEachProjectRoleForEveryHarness(t *testing.T) {
	project := rolesProject(t)

	stdout, code := run(t, newSystem(t, project), "setup")

	if code != 0 {
		t.Fatalf("exit code = %d, want 0", code)
	}
	for path, wantStart := range map[string]string{
		".claude/agents/reviewer.md":   "---\n" + header + "name: reviewer\ndescription: Reviews diffs.\nmodel: sonnet\n",
		".codex/agents/reviewer.toml":  header + "name = \"reviewer\"\ndescription = \"Reviews diffs.\"\nmodel = \"gpt-6-mini\"\n",
		".opencode/agents/reviewer.md": "---\n" + header + "description: Reviews diffs.\nmode: subagent\nmodel: openai/gpt-6-mini\n",
	} {
		content := readFile(t, filepath.Join(project, path))
		if !strings.HasPrefix(content, wantStart) || !strings.Contains(content, "Review the diff.\n") {
			t.Errorf("%s:\n%s\nwant it to start with:\n%s", path, content, wantStart)
		}
	}
	for _, path := range []string{".claude/agents/main.md", ".codex/agents/main.toml", ".opencode/agents/main.md"} {
		if _, ok := tree(t, project)[path]; ok {
			t.Errorf("wrote %s for the main Role", path)
		}
	}
	wantTail := "  ok         .claude/skills\n" +
		"  created    .claude/agents/reviewer.md\n" +
		"  created    .codex/agents/reviewer.toml\n" +
		"  created    .opencode/agents/reviewer.md\n" +
		"  ok         triage labels\n"
	if !strings.HasSuffix(stdout, wantTail) {
		t.Fatalf("stdout:\n%s\nwant it to end with:\n%s", stdout, wantTail)
	}
}

func TestSetupSecondRunWithUnchangedRolesChangesNothing(t *testing.T) {
	project := rolesProject(t)
	sys := newSystem(t, project)
	if _, code := run(t, sys, "setup"); code != 0 {
		t.Fatalf("first run exit code = %d", code)
	}
	before := tree(t, project)

	stdout, code := run(t, sys, "setup")

	if code != 0 {
		t.Fatalf("exit code = %d, want 0", code)
	}
	if after := tree(t, project); !reflect.DeepEqual(after, before) {
		t.Fatal("second run changed the project")
	}
	if strings.Contains(stdout, "created") || strings.Contains(stdout, "refreshed") {
		t.Fatalf("second run reported changes:\n%s", stdout)
	}
}

func TestSetupRefreshesOnlyTheAgentFilesAnEditedRoleChanges(t *testing.T) {
	project := rolesProject(t)
	sys := newSystem(t, project)
	if _, code := run(t, sys, "setup"); code != 0 {
		t.Fatalf("first run exit code = %d", code)
	}
	before := tree(t, project)
	// Only the Codex Model changes, so only the Codex file differs.
	roles := filepath.Join(project, ".agents", "roles.yaml")
	mustWrite(t, roles, strings.Replace(readFile(t, roles), "codex: gpt-6-mini", "codex: gpt-6-max", 1))

	stdout, code := run(t, sys, "setup")

	if code != 0 {
		t.Fatalf("exit code = %d, want 0", code)
	}
	after := tree(t, project)
	var changed []string
	for path, content := range after {
		if before[path] != content {
			changed = append(changed, path)
		}
	}
	slices.Sort(changed)
	if want := []string{".agents/roles.yaml", ".codex/agents/reviewer.toml"}; !slices.Equal(changed, want) {
		t.Fatalf("changed %v, want %v", changed, want)
	}
	wantTail := "  ok         .claude/agents/reviewer.md\n" +
		"  refreshed  .codex/agents/reviewer.toml\n" +
		"  ok         .opencode/agents/reviewer.md\n" +
		"  ok         triage labels\n"
	if !strings.HasSuffix(stdout, wantTail) {
		t.Fatalf("stdout:\n%s\nwant it to end with:\n%s", stdout, wantTail)
	}
}

func TestSetupCheckListsAgentFilesAsMissingStaleOrOKWithoutWriting(t *testing.T) {
	project := rolesProject(t)
	sys := newSystem(t, project)
	stdout, code := run(t, sys, "setup", "--check")
	if code != 1 {
		t.Fatalf("check exit code = %d, want 1: --check fails while files are missing", code)
	}
	wantTail := "  missing    .claude/agents/reviewer.md\n" +
		"  missing    .codex/agents/reviewer.toml\n" +
		"  missing    .opencode/agents/reviewer.md\n" +
		"  ok         triage labels\n"
	if !strings.HasSuffix(stdout, wantTail) {
		t.Fatalf("stdout before setup:\n%s\nwant it to end with:\n%s", stdout, wantTail)
	}
	if _, code := run(t, sys, "setup"); code != 0 {
		t.Fatalf("setup exit code = %d", code)
	}
	prompt := filepath.Join(project, ".agents", "roles", "reviewer.md")
	mustWrite(t, prompt, "Review the diff carefully.\n")
	before := tree(t, project)

	stdout, code = run(t, sys, "setup", "--check")

	if code != 1 {
		t.Fatalf("exit code = %d, want 1", code)
	}
	if !reflect.DeepEqual(tree(t, project), before) {
		t.Fatal("setup --check wrote into the project")
	}
	wantTail = "  stale      .claude/agents/reviewer.md\n" +
		"  stale      .codex/agents/reviewer.toml\n" +
		"  stale      .opencode/agents/reviewer.md\n" +
		"  ok         triage labels\n"
	if !strings.HasSuffix(stdout, wantTail) {
		t.Fatalf("stdout after editing the prompt:\n%s\nwant it to end with:\n%s", stdout, wantTail)
	}
}

func TestSetupLeavesAHandWrittenAgentFileUntouched(t *testing.T) {
	project := rolesProject(t)
	path := filepath.Join(project, ".claude", "agents", "reviewer.md")
	mustWrite(t, path, "---\nname: reviewer\n---\n\nMy own reviewer.\n")

	stdout, code := run(t, newSystem(t, project), "setup")

	if code != 0 {
		t.Fatalf("exit code = %d, want 0", code)
	}
	if got := readFile(t, path); got != "---\nname: reviewer\n---\n\nMy own reviewer.\n" {
		t.Fatalf("hand-written agent file changed:\n%s", got)
	}
	if !strings.Contains(stdout, "  conflict   .claude/agents/reviewer.md (not generated by overlord; left untouched)\n") {
		t.Fatalf("stdout does not report the conflict:\n%s", stdout)
	}
}

func TestSetupRestrictsAReadOnlyRoleInItsClaudeAndOpenCodeFiles(t *testing.T) {
	project := rolesProject(t)

	if _, code := run(t, newSystem(t, project), "setup"); code != 0 {
		t.Fatalf("exit code = %d, want 0", code)
	}

	// Codex agent files have no read-only setting, so only these two carry it.
	for path, restriction := range map[string]string{
		".claude/agents/reviewer.md": "model: sonnet\ntools: Read, Grep, Glob, Bash, WebFetch, WebSearch\n---\n",
		".opencode/agents/reviewer.md": "model: openai/gpt-6-mini\npermissions:\n" +
			"  - action: edit\n    resource: \"*\"\n    effect: deny\n" +
			"  - action: shell\n    resource: \"*\"\n    effect: deny\n---\n",
	} {
		if content := readFile(t, filepath.Join(project, path)); !strings.Contains(content, restriction) {
			t.Errorf("%s:\n%s\nwant the read-only restriction:\n%s", path, content, restriction)
		}
	}
}
