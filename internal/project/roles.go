package project

import (
	"bytes"
	"errors"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/PoeAudits/overlord/internal/catalog"
	"github.com/PoeAudits/overlord/internal/harness"
	"github.com/PoeAudits/overlord/internal/templates"
)

// agentDirs are where each Harness reads a Project's agent files.
var agentDirs = map[harness.Harness]string{
	harness.Claude:   ".claude/agents",
	harness.Codex:    ".codex/agents",
	harness.OpenCode: ".opencode/agents",
}

// agentFiles expands a generated item into one item per rendered agent file,
// or none when the Project has no roles file. Prompt paths are relative to the
// roles file's directory, as in ~/.agents.
func agentFiles(root string, item templates.Item) ([]templates.Item, error) {
	dir := filepath.Dir(item.Path)
	roles, err := catalog.LoadRoles(filepath.Join(root, dir))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var items []templates.Item
	for _, role := range roles {
		for _, file := range harness.RenderRole(role, filepath.ToSlash(filepath.Join(dir, "roles"))) {
			items = append(items, templates.Item{
				Path:     agentDirs[file.Harness] + "/" + file.Name,
				Strategy: templates.Generated,
				Content:  file.Content,
			})
		}
	}
	return items, nil
}

// generatedStatus compares the agent file at path with the rendered one. A
// file without the generated header is the Project's own and is not replaced.
func generatedStatus(path string, rendered []byte) (Status, string, error) {
	content, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return Missing, "", nil
	}
	if err != nil {
		return "", "", err
	}
	if !harness.IsGenerated(content) {
		return Conflict, "not generated by overlord; left untouched", nil
	}
	if !bytes.Equal(content, rendered) {
		return Stale, "", nil
	}
	return OK, "", nil
}
