// Package harness holds one adapter per Harness: where its files live, its
// agent file format, its model config writer and its hook installer.
package harness

import (
	"fmt"
	"strings"

	"github.com/PoeAudits/overlord/internal/catalog"
	"gopkg.in/yaml.v3"
)

// Harness is a coding-agent tool Overlord configures.
type Harness string

const (
	Claude   Harness = "claude"
	Codex    Harness = "codex"
	OpenCode Harness = "opencode"
)

// AgentFile is one rendered agent definition. Name is the file name inside
// the Harness's agents directory; callers choose that directory.
type AgentFile struct {
	Harness Harness
	Name    string
	Content []byte
}

// generatedMarker starts the header comment of every rendered agent file.
const generatedMarker = "generated by overlord from "

// RenderRole renders role into one agent file per Harness. source names where
// the Role is edited (for example ~/.agents/roles) and appears in each file's
// header. The main Role yields no files.
func RenderRole(role catalog.Role, source string) []AgentFile {
	if role.Name == catalog.MainRole {
		return nil
	}
	header := generatedMarker + source + "; edit there"
	description := role.Description
	if role.UserInvokedOnly {
		// Frontmatter cannot block invocation, so the description is the only
		// place to tell other agents not to call this Role.
		description = "Do not invoke unless the user explicitly requests the " + role.Name + " agent by name. " + description
	}
	prompt := strings.TrimRight(role.Prompt, "\n") + "\n"

	claude := []string{"name: " + yamlScalar(role.Name), "description: " + yamlScalar(description), "model: " + yamlScalar(role.Models.Claude)}
	if role.ReadOnly {
		claude = append(claude, "tools: Read, Grep, Glob, Bash, WebFetch, WebSearch")
	}
	opencode := []string{"description: " + yamlScalar(description), "mode: subagent", "model: " + yamlScalar(role.Models.OpenCode)}
	if role.ReadOnly {
		opencode = append(opencode, "tools:", "  write: false", "  edit: false", "  bash: false")
	}
	codex := []string{
		"# " + header,
		"name = " + tomlString(role.Name),
		"description = " + tomlString(description),
		"model = " + tomlString(role.Models.Codex),
	}
	if role.CodexReasoningEffort != "" {
		codex = append(codex, "model_reasoning_effort = "+tomlString(role.CodexReasoningEffort))
	}
	codex = append(codex, `developer_instructions = """`, tomlMultiline(prompt)+`"""`)

	return []AgentFile{
		{Harness: Claude, Name: role.Name + ".md", Content: markdown(header, claude, prompt)},
		{Harness: Codex, Name: role.Name + ".toml", Content: []byte(strings.Join(codex, "\n") + "\n")},
		{Harness: OpenCode, Name: role.Name + ".md", Content: markdown(header, opencode, prompt)},
	}
}

// markdown builds an agent file with YAML frontmatter. The header comment goes
// inside the frontmatter because both Harnesses require the file to start with
// the opening "---".
func markdown(header string, frontmatter []string, prompt string) []byte {
	return []byte("---\n# " + header + "\n" + strings.Join(frontmatter, "\n") + "\n---\n\n" + prompt)
}

// yamlScalar quotes s only when YAML needs it.
func yamlScalar(s string) string {
	out, err := yaml.Marshal(s)
	if err != nil {
		panic(fmt.Sprintf("marshal string %q: %v", s, err))
	}
	return strings.TrimSuffix(string(out), "\n")
}

// tomlString renders s as a TOML basic string.
func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// tomlMultiline escapes s for the body of a TOML multi-line basic string.
// Breaking every run of three quotes keeps the closing delimiter unambiguous.
func tomlMultiline(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), `"""`, `""\"`)
}

// IsGenerated reports whether content carries the header RenderRole writes:
// on the first line of a TOML file, or the first line inside Markdown
// frontmatter.
func IsGenerated(content []byte) bool {
	text := strings.TrimPrefix(string(content), "---\n")
	return strings.HasPrefix(text, "# "+generatedMarker)
}
