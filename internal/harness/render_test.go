package harness_test

import (
	"os"
	"path/filepath"
	"slices"
	"testing"

	"github.com/PoeAudits/overlord/internal/catalog"
	"github.com/PoeAudits/overlord/internal/harness"
)

const source = "~/.agents/roles"

func TestRenderRoleMatchesTheGoldenFileForEveryHarness(t *testing.T) {
	roles := loadTestRoles(t)
	extension := map[harness.Harness]string{harness.Claude: ".md", harness.Codex: ".toml", harness.OpenCode: ".md"}

	for _, name := range []string{"explorer", "restricted"} {
		files := harness.RenderRole(roles[name], source)

		var harnesses []harness.Harness
		for _, file := range files {
			harnesses = append(harnesses, file.Harness)
		}
		if want := []harness.Harness{harness.Claude, harness.Codex, harness.OpenCode}; !slices.Equal(harnesses, want) {
			t.Fatalf("%s rendered files for %v, want one each for %v", name, harnesses, want)
		}
		for _, file := range files {
			if file.Name != name+extension[file.Harness] {
				t.Errorf("%s file name for %s = %q", name, file.Harness, file.Name)
			}
			golden := filepath.Join("testdata", "golden", name+"."+string(file.Harness)+extension[file.Harness])
			want, err := os.ReadFile(golden)
			if err != nil {
				t.Fatal(err)
			}
			if string(file.Content) != string(want) {
				t.Errorf("%s:\n%s\nwant:\n%s", golden, file.Content, want)
			}
		}
	}
}

func TestRenderRoleYieldsNoAgentFileForMain(t *testing.T) {
	if files := harness.RenderRole(loadTestRoles(t)["main"], source); len(files) != 0 {
		t.Fatalf("main rendered %d files, want none", len(files))
	}
}

func loadTestRoles(t *testing.T) map[string]catalog.Role {
	t.Helper()
	roles, err := catalog.LoadRoles(filepath.Join("testdata", "agents"))
	if err != nil {
		t.Fatal(err)
	}
	byName := map[string]catalog.Role{}
	for _, role := range roles {
		byName[role.Name] = role
	}
	return byName
}

func TestIsGeneratedRecognisesRenderedFilesOnly(t *testing.T) {
	for _, file := range harness.RenderRole(loadTestRoles(t)["explorer"], ".agents/roles") {
		if !harness.IsGenerated(file.Content) {
			t.Errorf("%s file for %s is not recognised as generated", file.Name, file.Harness)
		}
	}
	handWritten := []string{
		"---\nname: explorer\ndescription: mine\n---\n\nPrompt mentioning generated by overlord from somewhere.\n",
		"name = \"explorer\"\n# generated by overlord from ~/.agents/roles; edit there\n",
		"",
	}
	for _, content := range handWritten {
		if harness.IsGenerated([]byte(content)) {
			t.Errorf("hand-written file recognised as generated:\n%s", content)
		}
	}
}
