package harness

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"

	"github.com/PoeAudits/overlord/internal/jsonedit"
)

// SyncCommand is what every session hook runs.
const SyncCommand = "overlord sync --quiet"

// OpenCodePlugin is the OpenCode plugin that runs SyncCommand when a session
// is created. OpenCode has no hooks file, so this is its session hook.
//
//go:embed opencode-sync.js
var OpenCodePlugin []byte

// IsGeneratedPlugin reports whether content carries OpenCodePlugin's header,
// so Sync may replace it with the current plugin.
func IsGeneratedPlugin(content []byte) bool {
	return bytes.HasPrefix(content, []byte("// generated by overlord sync"))
}

// sessionStartGroup is the matcher group Sync adds. It has no matcher, so it
// runs for every kind of session start. Field order is the output order.
type sessionStartGroup struct {
	Hooks []commandHook `json:"hooks"`
}

type commandHook struct {
	Type    string `json:"type"`
	Command string `json:"command"`
}

// EnsureSessionStartHook returns a hooks file (Claude Code's settings.json or
// Codex's hooks.json, which share the "hooks" shape) with a SessionStart hook
// running SyncCommand. Content already holding such a hook is returned as is;
// otherwise the hook is added in place and every other byte is kept. Empty
// content stands for an absent file.
func EnsureSessionStartHook(content []byte) ([]byte, error) {
	doc, err := jsonedit.Document(content)
	if err != nil {
		return nil, err
	}
	root, err := jsonedit.Object(doc)
	if err != nil {
		return nil, err
	}
	group := sessionStartGroup{Hooks: []commandHook{{Type: "command", Command: SyncCommand}}}
	hooks, found, err := jsonedit.Member(doc, root, "hooks")
	if err != nil {
		return nil, err
	}
	if !found {
		return jsonedit.InsertMember(doc, root, "hooks", map[string]any{"SessionStart": []sessionStartGroup{group}}), nil
	}
	if doc[hooks.Start] != '{' {
		return nil, fmt.Errorf(`"hooks" is not an object`)
	}
	sessionStart, found, err := jsonedit.Member(doc, hooks, "SessionStart")
	if err != nil {
		return nil, err
	}
	if !found {
		return jsonedit.InsertMember(doc, hooks, "SessionStart", []sessionStartGroup{group}), nil
	}
	var groups []sessionStartGroup
	if err := json.Unmarshal(doc[sessionStart.Start:sessionStart.End], &groups); err != nil {
		return nil, fmt.Errorf(`"hooks.SessionStart": %w`, err)
	}
	for _, existing := range groups {
		for _, hook := range existing.Hooks {
			if hook.Command == SyncCommand {
				return doc, nil
			}
		}
	}
	return jsonedit.AppendElement(doc, sessionStart, group), nil
}
